import requests

def chat_with_anastasiya(your_message):

    memories = load_from_file()
    memory_text = "\n" .join([f"-{m}"for m in memories])

    api_key = "YOUR_GEMINI_KEY_HERE"

    response = requests.post(
        f"https://generativelanguage.googleapis.com/v1/models/gemini-2.5-flash:generateContent?key={api_key}",
        json={
            "contents": [{
                "parts": [{
                    "text": f"You know this about the user:\n{memory_text}\n\nUsersays: {your_message}:"
                }]
            }]

        }

    )

    result = response.json()
    # Handle potential API errors where 'candidates' might not be present
    if 'candidates' not in result:
        print("API response did not contain 'candidates'. Full response:")
        print(result)
        return "Error: Could not get a response from Gemini."
    return result['candidates'] [0] ['content'] ['parts'] [0] ['text']

