import json
def save_to_file(memory_list):
  with open('memories.json' ,'w') as f:
    json.dump(memory_list, f)
  print("Memories saved to file !")

def load_from_file():
  try:
    with open('memories.json' , 'r') as f :
      return json.load(f)
  except:
    return []
# Test it
